/* 像素级画点：对帧缓冲区(x,y)位置写1或0，自动转换页/位并标记脏页 */
void OLED_DrawPixel(uint8_t x, uint8_t y, uint8_t color)
{
    if (x >= 128 || y >= 64) return;
    uint8_t page = y / 8;
    uint8_t bit  = y % 8;
    if (color)
        oled_buf[x][page] |=  (1 << bit);
    else
        oled_buf[x][page] &= ~(1 << bit);
    mark_dirty(page);
}

/* 页寻址脏页刷新：仅发送标记页，逐字节事务，I2C流量与脏页数成正比 */
void OLED_Refresh(void)
{
    for (uint8_t page = 0; page < 8; page++)
    {
        if (!dirty_page[page]) continue;

        oled_write_cmd(0xB0 | page);
        oled_write_cmd(0x00);
        oled_write_cmd(0x10);

        for (uint8_t col = 0; col < 128; col++) {
            uint8_t tmp[2] = {0x40, oled_buf[col][page]};
            oled_i2c_write(tmp, 2);
        }

        dirty_page[page] = 0;
    }
}
